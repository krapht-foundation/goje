const (
	builtinColumns = 16
	builtinWidth   = 6
	builtinHeight  = 8
)

var builtin = sync.OnceValue(func() Face {
	pixels := image.NewNRGBA(
		image.Rect(0, 0, builtinColumns*builtinWidth, len(builtinGlyphs)*builtinHeight),
	)
	for strip, rows := range builtinGlyphs {
		for y, row := range rows {
			for x := range len(row) {
				if row[x] == '#' {
					pixels.SetNRGBA(x, strip*builtinHeight+y, color.NRGBA{R: 255, G: 255, B: 255, A: 255})
				}
			}
		}
	}
	return newFace(
		pixels,
		image.Pt(builtinWidth, builtinHeight),
		builtinHeight-1,
		' ',
		'~'-' '+1,
		nil,
	)
})

// Builtin returns Goje's 5 × 7 font for ASCII U+0020 to U+007E in 6 × 8 cells,
// drawn white on transparent so that ImageTinted can color it. Its baseline is
// 7 and its glyphs are monospaced. The sheet is built once and shared; place it
// in the launch atlas with InAtlas like any other face.
func Builtin() Face { return builtin() }
